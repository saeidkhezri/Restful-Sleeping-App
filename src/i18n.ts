function toFaDigits(n: number | string): string {
  return String(n).replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
}

export function digits(s: string | number, lang: Lang): string {
  return lang === "fa" ? toFaDigits(s) : String(s);
}

